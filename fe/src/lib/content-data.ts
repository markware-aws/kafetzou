/**
 * Build-time access to the guide content. Import it ONLY from getStaticProps/getStaticPaths:
 * Next.js strips those imports from the client bundle, so the full JSON never ships to the
 * browser. Components receive just the slice they render through page props.
 */

import fs from "node:fs";
import path from "node:path";
import coffeeSymbolsJson from "@/content/coffee-symbols.json";
import tarotCardsJson from "@/content/tarot-cards.json";
import zodiacSignsJson from "@/content/zodiac-signs.json";
import zodiacPairsJson from "@/content/zodiac-compatibility.json";
import type { CoffeeSymbol } from "@/lib/coffee-symbols";
import type { TarotCard } from "@/lib/tarot-cards";
import type { DreamDictionary } from "@/lib/dream-dictionary";
import { SIGNS } from "@/lib/astrology";
import { ZODIAC_SLUGS, type ZodiacPair, type ZodiacSign, type ZodiacSignContent } from "@/lib/zodiac";

const coffeeSymbols = coffeeSymbolsJson as CoffeeSymbol[];
const tarotCards = tarotCardsJson as TarotCard[];
const zodiacPairs = zodiacPairsJson as ZodiacPair[];

function findOrThrow<T extends { slug: string }>(items: T[], slug: string, kind: string): T {
  const item = items.find((candidate) => candidate.slug === slug);
  if (!item) throw new Error(`Unknown ${kind} slug: ${slug}`);
  return item;
}

// ── Coffee symbols ──────────────────────────────────────────────────────────

export function getCoffeeSymbols(): CoffeeSymbol[] {
  return coffeeSymbols;
}

export function getCoffeeSymbol(slug: string): CoffeeSymbol {
  return findOrThrow(coffeeSymbols, slug, "coffee symbol");
}

// ── Tarot ───────────────────────────────────────────────────────────────────

export function getTarotCards(): TarotCard[] {
  return tarotCards;
}

export function getTarotCard(slug: string): TarotCard {
  return findOrThrow(tarotCards, slug, "tarot card");
}

// ── Zodiac ──────────────────────────────────────────────────────────────────

const zodiacSigns: ZodiacSign[] = (zodiacSignsJson as ZodiacSignContent[]).map((content) => {
  const sign = SIGNS[ZODIAC_SLUGS.indexOf(content.slug as (typeof ZODIAC_SLUGS)[number])];
  if (!sign || sign.id !== content.id) {
    throw new Error(`Zodiac content out of order or mismatched: ${content.slug}`);
  }
  return { ...content, symbol: sign.symbol, element: sign.element, dates: sign.dates };
});

export function getZodiacSigns(): ZodiacSign[] {
  return zodiacSigns;
}

export function getZodiacSign(slug: string): ZodiacSign {
  return findOrThrow(zodiacSigns, slug, "zodiac sign");
}

export function getZodiacPairs(): ZodiacPair[] {
  return zodiacPairs;
}

export function getZodiacPair(slug: string): ZodiacPair {
  return findOrThrow(zodiacPairs, slug, "zodiac pair");
}

/** Every pair that includes the sign, in zodiac order of the partner sign. */
export function getPairsForSign(slug: string): ZodiacPair[] {
  return ZODIAC_SLUGS.map((partner) =>
    zodiacPairs.find(
      (pair) =>
        (pair.signs[0] === slug && pair.signs[1] === partner) ||
        (pair.signs[1] === slug && pair.signs[0] === partner),
    ),
  ).filter((pair): pair is ZodiacPair => pair !== undefined);
}

// ── Dream dictionary ────────────────────────────────────────────────────────

/** The same file the app's live search fetches; generated by scripts/build-dream-dictionary.py. */
export function getDreamDictionary(): DreamDictionary {
  const file = path.join(process.cwd(), "public/data/dream-dictionary.json");
  return JSON.parse(fs.readFileSync(file, "utf8")) as DreamDictionary;
}
